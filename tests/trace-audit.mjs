// tests/trace-audit.mjs — the honest answer to "are ALL traces gone and is the
// quality identical?". Proves stream identity for video (bit-for-bit) and lists
// what survives the clean, so nothing is claimed that has not been measured.
// Run: node tests/trace-audit.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { requireMediaTools } from './lib/tools.mjs';

requireMediaTools();
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(here, '..');
const fx = resolve(here, 'fixtures');
const out = resolve(here, 'out', 'audit');
mkdirSync(out, { recursive: true });

const html = readFileSync(resolve(rootDir, 'index.html'), 'utf8');
const m = /\/\* ===== CLEANSLATE CORE[\s\S]*?\/\* ===== END CLEANSLATE CORE ===== \*\//.exec(html);
(0, eval)(m[0]);
const core = globalThis.CleanSlateCore;

const ff = (args) => execFileSync(args[0], args.slice(1), { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
// hash of the DECODED video frames: deep clean changes the compressed stream
// (encoder SEI is neutralised) while every decoded frame stays byte-identical
const frameHash = (file) => { try { return ff(['ffmpeg', '-v', 'error', '-i', file, '-map', '0:v', '-f', 'framemd5', '-']).replace(/^#.*\n/gm, '').trim().split('\n').slice(-1)[0]; } catch (e) { return 'n/a'; } };
const audioHash = (file) => { try { return ff(['ffmpeg', '-v', 'error', '-i', file, '-map', '0:a', '-f', 'md5', '-']).trim(); } catch (e) { return 'n/a'; } };

const NEEDLES = [
  'c2pa', 'jumb', 'trainedAlgorithmicMedia', 'Content Credentials', 'xmpmeta', 'Iptc4xmpExt',
  'ilst', 'udta', 'loci', 'emsg', '©xyz', '©too', '©nam', 'mdta',
  'Veo', 'DALL', 'Midjourney', 'Stable Diffusion', 'ComfyUI', 'Firefly', 'Seedream', 'HeyGen', 'ElevenLabs',
  'made with AI', 'generated by AI', 'prompt', 'parameters', 'workflow',
  'x264', 'x265', 'Lavf', 'Lavc', 'libx264', 'VideoLAN', 'options:', 'encoder', 'software', 'title',
  'GPS', '52.63', 'Coventry', 'beach',
];
// NOTE: Uint8Array.includes() takes a NUMBER, so scanning one with a Buffer needle
// silently returns false for everything. Always convert to a Buffer first.
const scan = (bytes) => {
  const buf = Buffer.isBuffer(bytes) ? bytes : Buffer.from(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  return NEEDLES.filter((n) => buf.includes(Buffer.from(n)));
};

console.log('=== VIDEO: deep clean — no machine traces, identical decoded frames ===');
for (const name of readdirSync(fx).filter((f) => /\.(mp4|mov|m4v)$/i.test(f)).sort()) {
  const src = resolve(fx, name);
  const buf = readFileSync(src);
  const a = core.analyseVideo(new Uint8Array(buf));
  const res = core.cleanVideo(new Uint8Array(buf), a);
  const outPath = resolve(out, name.replace(/\.(mp4|mov|m4v)$/, '') + '.cleaned.' + name.split('.').pop());
  writeFileSync(outPath, res.bytes);
  const v1 = frameHash(src), v2 = frameHash(outPath);
  const hasAudio = ff(['ffprobe', '-v', 'error', '-select_streams', 'a', '-show_entries', 'stream=index', '-of', 'csv=p=0', src]).trim() !== '';
  const a1 = hasAudio ? audioHash(src) : '', a2 = hasAudio ? audioHash(outPath) : '';
  const before = scan(buf), after = scan(res.bytes);
  console.log(`\n${name}  [${res.mode}${res.deep ? ' + deep' : ''}] zeroed ${res.zeroed} B`);
  console.log(`  decoded frame hash  original=${v1} cleaned=${v2}  ${v1 === v2 ? 'IDENTICAL' : 'DIFFERENT'}`);
  if (hasAudio) console.log(`  decoded audio hash  original=${a1} cleaned=${a2}  ${a1 === a2 ? 'IDENTICAL' : 'DIFFERENT'}`);
  console.log(`  traces before: ${before.join(', ') || '(none)'}`);
  console.log(`  traces after : ${after.join(', ') || '(none)'}`);
}

console.log('\n=== IMAGES: lossless strip — tags deleted, pixels untouched ===');
for (const name of readdirSync(fx).filter((f) => /\.(jpg|png|webp)$/i.test(f)).sort()) {
  const buf = readFileSync(resolve(fx, name));
  const u8 = new Uint8Array(buf);
  const before = scan(buf);
  const res = core.stripImageLossless(u8, await core.analyse(u8, 'image', name));
  const after = scan(res.bytes);
  console.log(`  ${name}: removed ${res.removed.length} item(s); traces before: ${before.join(', ') || '(none)'} | after: ${after.join(', ') || '(none)'}`);
}

console.log('\nNote: strings the encoder wrote into the compressed stream itself (x264/x265 SEI user data)');
