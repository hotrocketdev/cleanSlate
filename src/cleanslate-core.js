  /* ---------------- PNG ---------------- */
  async function inflate(u, raw) {
    try {
      const ds = new DecompressionStream(raw ? 'deflate-raw' : 'deflate');
      const stream = new Blob([u]).stream().pipeThrough(ds);
      return new Uint8Array(await new Response(stream).arrayBuffer());
    } catch (e) {
      return null;
    }
  }

