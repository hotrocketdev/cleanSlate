  function strings(u, opts) {
    const min = (opts && opts.min) || 4;
    const cap = (opts && opts.cap) || 12;
    const out = [];
    let cur = '';
    for (let i = 0; i < u.length; i++) {
      const c = u[i];
      if (c >= 32 && c <= 126) cur += String.fromCharCode(c);
      else {
        if (cur.length >= min) { out.push(cur); if (out.length >= cap) return out; }
        cur = '';
      }
    }
    if (cur.length >= min && out.length < cap) out.push(cur);
    return out;
  }

