  function parseTiff(u, tiff, where, path) {
    const out = [];
    if (tiff + 8 > u.length) return out;
    const order = latin1(u, tiff, tiff + 2);
    if (order !== 'II' && order !== 'MM') return out;
    const r16 = order === 'II' ? (o) => u[o] | (u[o + 1] << 8) : (o) => be16(u, o);
    const r32 = order === 'II' ? (o) => le32(u, o) : (o) => be32(u, o);
    const seen = new Set();
    let guard = 0;
    const queue = [[r32(tiff + 4), '']];
    while (queue.length && guard++ < 24) {
      const [ifdOff, label] = queue.shift();
      if (!ifdOff || seen.has(ifdOff) || tiff + ifdOff + 2 > u.length) continue;
      seen.add(ifdOff);
      const n = r16(tiff + ifdOff);
      for (let i = 0; i < n; i++) {
        const eo = tiff + ifdOff + 2 + i * 12;
        if (eo + 12 > u.length) break;
        const tag = r16(eo);
        const info = EXIF_TAGS[tag];
        if (tag === 0x8769) { queue.push([r32(eo + 8), 'exif']); continue; }
        if (tag === 0x8825) { queue.push([r32(eo + 8), 'gps']); continue; }
        if (label === 'gps') {
          const gname = GPS_TAGS[tag];
          if (gname) out.push(finding({ where, path: path + '/gps', name: gname, value: exifValue(u, tiff, eo) }));
          continue;
        }
        if (!info) continue;
        const val = exifValue(u, tiff, eo);
        if (val === '') continue;
        out.push(finding({ where, path: path + (label ? '/' + label : '') + '/' + info[0], name: info[0], value: val }));
      }
    }
    return out;
  }

