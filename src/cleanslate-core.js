  function readBoxes(u, start, end) {
    const out = [];
    let p = start;
    while (p + 8 <= end) {
      let size = be32(u, p);
      let header = 8;
      if (size === 1) {
        if (p + 16 > end) break;
        size = be64(u, p + 8);
        header = 16;
      } else if (size === 0) {
        size = end - p;
      }
      if (size < header || p + size > end) break;
      out.push({ type: latin1(u, p + 4, p + 8), start: p, header, size, end: p + size });
      p += size;
    }
    return out;
  }

