  function scanWebp(u) {
    const findings = [];
    const notes = [];
    let p = 12;
    while (p + 8 <= u.length) {
      const type = latin1(u, p, p + 4);
      const len = le32(u, p + 4);
      if (p + 8 + len > u.length) break;
      const body = u.subarray(p + 8, p + 8 + len);
      const path = '/WEBP:' + type.trim();
      if (type === 'EXIF') {
        const head = latin1(body, 0, 4) === 'Exif' ? p + 14 : p + 8;
        findings.push(...parseTiff(u, head, 'EXIF', path));
      } else if (type === 'XMP ') {
        findings.push(...xmpFindings(DEC8.decode(body), 'XMP', path));
      } else if (type === 'ICCP') {
        const zero = body.indexOf(0);
        findings.push(finding({ where: 'ICC', path, name: 'ICC colour profile', value: latin1(body, 0, zero < 0 ? 20 : zero) }));
      } else if (type === 'VP8X') {
        const flags = body[0];
        if (flags & 0x08) notes.push('EXIF flag set in VP8X');
        if (flags & 0x04) notes.push('XMP flag set in VP8X');
        if (flags & 0x02) notes.push('Animated WebP — the cleaned file keeps the first frame as a still');
      } else if (type === 'ANIM' || type === 'ANMF') {
        if (!notes.some((n) => n.indexOf('Animated') === 0)) notes.push('Animated WebP — the cleaned file keeps the first frame as a still');
      }
      p += 8 + len + (len % 2);
    }
    return { format: 'WebP', findings, notes };
  }

